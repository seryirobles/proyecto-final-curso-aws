"""Source scans for the shared kernel: one name fold, one unit vocabulary, ASCII only.

R2, R16 and R22 are negative claims about the whole planner_core package, so no
call site can prove them and only a scan of the sources can. Built to the
discipline `test_no_ambient_time.py` arrived at: every scan asserts its own
pattern matches inside the module it exempts, and asserts the scanned file list
is non-empty and contains named modules, so no guard can pass by matching
nothing.

The scans read `src/planner_core` only, so this module -- which is where the
banned patterns are spelled out -- needs no self-exclusion.

Why the fold scan bans a bare `.lower()` as well: on its own it cannot implement
the accent rule, but used as a merge key in a later feature it would be a second
fold, and a wrong one. A genuine unrelated need for it routes through
`normalize` or comes back through review. That friction is the point.
"""

from __future__ import annotations

import re
from pathlib import Path

TESTS_ROOT = Path(__file__).resolve().parent
CORE_SRC = TESTS_ROOT.parent / "src" / "planner_core"

NAME_FOLD_SOURCE = CORE_SRC / "domain" / "text.py"
UNIT_VOCABULARY_SOURCE = CORE_SRC / "domain" / "units.py"

SHARED_KERNEL_MODULES = (NAME_FOLD_SOURCE, UNIT_VOCABULARY_SOURCE)

NAME_FOLD = re.compile(r"\bunicodedata\b|\bcasefold\b|\.lower\s*\(")

# A declaration, not a use: features 4, 7, 8 and 12 must import Unit freely, and
# only a second vocabulary is the offence.
UNIT_VOCABULARY = re.compile(
    r"^\s*class\s+\w*Unit\w*\b|^\s*(?:GRAM|MILLILITRE|LITRE|KILOGRAM)\b\s*(?::[^=]+)?="
)


def _matches(pattern: re.Pattern[str], sources: list[Path]) -> list[str]:
    """Every line of every source matching the pattern, located."""
    found: list[str] = []
    for source in sources:
        for number, line in enumerate(source.read_text(encoding="utf-8").splitlines(), start=1):
            hit = pattern.search(line)
            if hit:
                found.append(f"{source}:{number}: {line.strip()}")
    return found


def test_planner_core_has_one_name_fold() -> None:
    """R1, R2: two call sites folding differently produce keys that never match.

    docs/data_model.md section 2 says exactly this about the username
    reservation key, which is generated by this same helper, and instructs:
    "put it behind one shared helper".
    """
    for banned in ("unicodedata.normalize", "name.casefold()", "name.lower()", "value.lower ()"):
        assert NAME_FOLD.search(banned), banned

    assert not NAME_FOLD.search("# the lower bound is deliberate")
    assert not NAME_FOLD.search("from planner_core.domain.text import normalize")

    sources = [path for path in sorted(CORE_SRC.rglob("*.py")) if path != NAME_FOLD_SOURCE]

    assert sources, f"no planner_core sources found under {CORE_SRC}"
    assert UNIT_VOCABULARY_SOURCE in sources
    assert CORE_SRC / "domain" / "calendar.py" in sources
    assert NAME_FOLD_SOURCE.is_file(), NAME_FOLD_SOURCE
    assert _matches(NAME_FOLD, [NAME_FOLD_SOURCE]), NAME_FOLD_SOURCE

    assert _matches(NAME_FOLD, sources) == []


def test_planner_core_has_one_unit_vocabulary() -> None:
    """R16: a second unit vocabulary splits the shopping list permanently (G-39)."""
    for banned in (
        "class Unit(StrEnum):",
        "class ShoppingUnit(StrEnum):",
        "    class UnitOfMeasure:",
        '    GRAM = "g"',
        '    KILOGRAM: str = "kg"',
        'LITRE = "l"',
    ):
        assert UNIT_VOCABULARY.search(banned), banned

    assert not UNIT_VOCABULARY.search("from planner_core.domain.units import Unit")
    assert not UNIT_VOCABULARY.search("    return Unit.GRAM")
    assert not UNIT_VOCABULARY.search("    unit = parse_unit(code)")

    sources = [path for path in sorted(CORE_SRC.rglob("*.py")) if path != UNIT_VOCABULARY_SOURCE]

    assert sources, f"no planner_core sources found under {CORE_SRC}"
    assert NAME_FOLD_SOURCE in sources
    assert CORE_SRC / "domain" / "calendar.py" in sources
    assert UNIT_VOCABULARY_SOURCE.is_file(), UNIT_VOCABULARY_SOURCE
    assert _matches(UNIT_VOCABULARY, [UNIT_VOCABULARY_SOURCE]), UNIT_VOCABULARY_SOURCE

    assert _matches(UNIT_VOCABULARY, sources) == []


def test_the_shared_kernel_modules_are_ascii_only() -> None:
    """R22: no Castilian literal, and no accented str.maketrans table, can enter these.

    The second half is what the check really buys: restricted to ASCII, the
    accent fold cannot be a hard-coded table of accented characters, which fails
    on decomposed input. It has to be the U+0303 rule (design.md section 7).

    The honest limitation feature 2 recorded still applies: an unaccented
    Spanish string such as "unidad" would slip past an ASCII check.
    """
    assert set(SHARED_KERNEL_MODULES) == {
        CORE_SRC / "domain" / "text.py",
        CORE_SRC / "domain" / "units.py",
    }

    for module in SHARED_KERNEL_MODULES:
        source = module.read_text(encoding="utf-8")
        assert source, f"{module} is empty"
        assert source.isascii(), f"{module} contains non-ASCII characters"
